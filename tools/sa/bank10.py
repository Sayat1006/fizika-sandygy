def gaslaw_task(r):
    p1 = r.choice([100, 150, 200]); V1 = r.choice([2, 3, 4]); V2 = V1 * r.choice([2, 3]); kind = r.choice(['T', 'p'])
    if kind == 'T':
        pts = [(V1 + (V2 - V1) * i / 20, p1 * V1 / (V1 + (V2 - V1) * i / 20)) for i in range(21)]
        fig = F.graph([pts], V2 + 1, p1 * 1.2, 1, p1 / 4, 'V, л', 'p, кПа')
        ans = (f'изотермиялық (T = const), Бойль–Мариотт заңы', f'p₂ = p₁V₁/V₂ = {n(p1 * V1 / V2)} кПа')
    else:
        fig = F.graph([[(V1, p1), (V2, p1)]], V2 + 1, p1 * 1.3, 1, p1 / 4, 'V, л', 'p, кПа')
        ans = ('изобаралық (p = const), Гей-Люссак заңы', f'T₂ = T₁V₂/V₁ = {300 * V2 // V1} К (T₁ = 300 К)')
    return {'stem': 'Тұрақты массалы идеал газ күйінің өзгерісі p–V графигінде көрсетілген.', 'fig': fig, 'figw': 9,
            'parts': [P('Процесті атаңыз және заңын жазыңыз.', ans[0], 2, ['процесті дұрыс атайды', 'заңның формуласын жазады']),
                      P('Газдың соңғы параметрін есептеңіз.' if kind == 'T' else 'Бастапқы температура 300 К болса, соңғы температураны есептеңіз.', ans[1]),
                      P('Менделеев–Клапейрон теңдеуін жазыңыз.', 'pV = (m/M)RT')],
            'level': 'Қолдану', 'kw': ['изопроцес', 'газ заң', 'Бойль', 'күйінің теңдеуі']}


