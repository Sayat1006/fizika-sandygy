def grating_task(r):
    N = r.choice([100, 200, 500]); lam = r.choice([500, 600, 650]); d = 1e-3 / N; k = 1; s = k * lam * 1e-9 / d; kmax = int(d / (lam * 1e-9))
    return {'stem': f'1 мм-де {N} штрихы бар дифракциялық торға толқын ұзындығы {lam} нм жарық перпендикуляр түседі.', 'fig': F2.grating(2), 'figw': 9,
            'parts': [P('Тордың периодын есептеңіз.', f'd = 1/{N} мм = {sci(d)} м'),
                      P('Дифракциялық тордың формуласын жазыңыз.', 'd·sinφ = kλ'),
                      P('Бірінші ретті максимумның бағытын табыңыз.', f'sinφ = λ/d = {n(s, 3)}; φ ≈ {n(math.degrees(math.asin(s)), 1)}°', 2, ['sinφ-ді есептейді', 'бұрышты табады']),
                      P('Байқалатын максимумның ең үлкен ретін табыңыз.', f'k_max = d/λ → {kmax}')],
            'level': 'Жоғары деңгей дағдылары', 'kw': ['дифракция', 'интерференция', 'тор']}


def interference_task(r):
    lam = r.choice([500, 600]); k = r.choice([3, 3.5, 4, 4.5]); dd = k * lam / 1000
    res = 'максимум (күшейеді) — жұп жарты толқын' if float(k).is_integer() else 'минимум (әлсірейді) — тақ жарты толқын'
    return {'stem': f'Екі когерентті толқынның жүріс айырымы Δd = {n(dd)} мкм, толқын ұзындығы {lam} нм.', 'fig': None,
            'parts': [P('Интерференция максимумының шартын жазыңыз.', 'Δd = kλ'),
                      P('Жүріс айырымында неше толқын ұзындығы бар?', f'Δd/λ = {n(k, 2)}'),
                      P('Бұл нүктеде жарық күшейе ме, әлсірей ме?', res, 2, ['шартпен салыстырады', 'дұрыс қорытынды жасайды']),
                      P('Когерентті толқындар деген не?', 'жиіліктері бірдей, фазалар айырымы тұрақты толқындар')],
            'level': 'Қолдану', 'kw': ['интерференция', 'когерент']}


