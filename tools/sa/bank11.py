    m = r.choice([0.1, 0.4, 0.9]); k = r.choice([10, 40, 100]); A = r.choice([0.02, 0.05]); T = 2 * math.pi * math.sqrt(m / k); vmax = A * math.sqrt(k / m)
    return {'stem': f'Массасы {n(m)} кг жүк қатаңдығы {k} Н/м серіппеде {n(A * 100)} см амплитудамен тербеледі.', 'fig': None,
            'parts': [P('Серіппелі маятниктің периодын есептеңіз.', f'T = 2π√(m/k) ≈ {n(T, 2)} с'),
                      P('Тербелістің толық механикалық энергиясын есептеңіз.', f'E = kA²/2 = {n(k * A * A / 2, 4)} Дж'),
                      P('Жүктің максимал жылдамдығын есептеңіз.', f'υ_max = A√(k/m) ≈ {n(vmax, 2)} м/с', 2, ['энергияның сақталуын қолданады', 'есептейді']),
                      P('Тепе-теңдік күйден өткенде энергияның қай түрі максимал?', 'кинетикалық')],
            'level': 'Қолдану', 'kw': ['серіппелі', 'маятник', 'тербеліс']}


