    return {'stem': f'Тербелмелі контур: L = {L} мГн, C = {Cc} мкФ.', 'fig': None,
            'parts': [P('Томсон формуласын жазыңыз.', 'T = 2π√(LC)'),
                      P('Меншікті тербеліс периоды мен жиілігін есептеңіз.', f'T ≈ {sci(T)} с; ν ≈ {n(1 / T, 0)} Гц', 2, ['периодты', 'жиілікті есептейді']),
                      P('Конденсатордың сыйымдылығын 4 есе арттырса, период қалай өзгереді?', '2 есе артады'),
                      P('Контурдағы энергияның түрленуін сипаттаңыз.', 'конденсатордың электр өрісінің энергиясы катушканың магнит өрісінің энергиясына айналады және керісінше')],
            'level': 'Қолдану', 'kw': ['тербелмелі контур', 'электромагниттік тербеліс']}


