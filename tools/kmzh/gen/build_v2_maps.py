for var, m in MAP.items():
    g = var.split('-')[0]
    items = V2[var]
    assert len(m) == len(items), (var, len(m), len(items))
    bases = sorted({v[0] for v in m.values() if isinstance(v, tuple)} | {g})
    lines = [f'# -*- coding: utf-8 -*-', f'"""ҚМЖ v2 – {var}: сабақ → спецификация (build_v2_maps.py жасаған)."""']
    for b in bases:
        lines.append(f'from v{b} import V as B{b}')
    lines += ['from g_v2new import S2', 'V = {}']
    for n in range(1, len(items) + 1):
        x = m[n]
        if x is None:          # тоқсандық жиынтық бағалау – спецификация керек емес
            continue
        if isinstance(x, str):
            lines.append(f"V[{n}] = {{'spec': S2[{x!r}]}}")
        else:
            bg, bn = x if isinstance(x, tuple) else (g, x)
            lines.append(f"V[{n}] = {{**B{bg}.get({bn}, {{}}), 'base': ({bg!r}, {bn})}}")
    open(os.path.join(HERE, f"v{var.replace('-', '_')}.py"), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
